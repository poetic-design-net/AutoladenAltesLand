/** Non-destructive homepage sync. Dry-run by default; publish with --apply. */
import { createClient } from '@sanity/client';
import { createReadStream } from 'node:fs';
import { readFile, mkdtemp, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { dirname, resolve, basename, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import dotenv from 'dotenv';

const here = dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: resolve(here, '.env'), quiet: true });
if (!process.env.SANITY_TOKEN) throw new Error('SANITY_TOKEN fehlt in studio/.env');
const apply = process.argv.includes('--apply');
const client = createClient({
  projectId: 'dgeh1xh8',
  dataset: 'production',
  apiVersion: '2025-01-01',
  token: process.env.SANITY_TOKEN,
  useCdn: false,
});
const { fallbackFrontpage: defaults } = JSON.parse(
  await readFile(resolve(here, '../src/data/content-defaults.json'), 'utf8')
);
const docs = await client.fetch('*[_id in ["frontpage", "drafts.frontpage"]]');
if (!docs.some((doc) => doc._id === 'frontpage'))
  throw new Error('Veröffentlichte Startseite fehlt; keine automatische Neuanlage.');

function fillMissing(existing, fallback) {
  if (existing === undefined || existing === null || existing === '')
    return structuredClone(fallback);
  if (Array.isArray(fallback) || typeof fallback !== 'object' || fallback === null) return existing;
  return Object.fromEntries(
    [...new Set([...Object.keys(existing), ...Object.keys(fallback)])].map((key) => [
      key,
      key in fallback ? fillMissing(existing[key], fallback[key]) : existing[key],
    ])
  );
}
function keyed(value, path = 'field') {
  if (Array.isArray(value))
    return value.map((item, index) =>
      typeof item === 'object' && item !== null
        ? { _key: item._key ?? `${path}-${index}`, ...keyed(item, `${path}-${index}`) }
        : item
    );
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, keyed(item, key)]));
}
async function image(filename, alt) {
  const file = resolve(here, '../public', filename);
  const sha1hash = createHash('sha1')
    .update(await readFile(file))
    .digest('hex');
  let asset = await client.fetch(
    '*[_type == "sanity.imageAsset" && sha1hash == $sha1hash][0]{_id}',
    { sha1hash }
  );
  if (!asset && apply)
    asset = await client.assets.upload('image', createReadStream(file), {
      filename: basename(file),
      label: alt,
    });
  return {
    _type: 'image',
    asset: { _type: 'reference', _ref: asset?._id ?? `pending-upload-${filename}` },
  };
}

if (apply) {
  const backup = join(await mkdtemp(join(tmpdir(), 'aal-sanity-backup-')), 'frontpage.json');
  await writeFile(backup, JSON.stringify(docs, null, 2), { mode: 0o600 });
  console.log(`Sicherung: ${backup}`);
}
const [desktopImage, mobileImage] = await Promise.all([
  image('hero-desktop-1672.webp', 'Alex – Desktop-Hero'),
  image('hero-mobile-941.webp', 'Alex – Mobile-Hero'),
]);
let transaction = client.transaction();
let count = 0;
for (const doc of docs) {
  const merged = fillMissing(doc, defaults);
  merged.hero.desktopImage = desktopImage;
  merged.hero.mobileImage = mobileImage;
  // Derived responsive URLs are generated by Astro, not stored as editable strings.
  delete merged.hero.desktopImageSmall;
  delete merged.hero.mobileImageSmall;
  delete merged.hero.portraitAlt;
  delete merged.about.imageAlt;
  merged.hero.ctaLabel = defaults.hero.ctaLabel;
  merged.intro.text = defaults.intro.text;
  merged.intro.promisesLabel = defaults.intro.promisesLabel;
  merged.process.intro = defaults.process.intro;
  const stepCopy = { kontakt: 0, wuensche: 1, lieferung: 3 };
  merged.process.steps = merged.process.steps.map((step) =>
    step._key in stepCopy
      ? { ...step, text: defaults.process.steps[stepCopy[step._key]].text }
      : step
  );
  merged.finance.helpText = defaults.finance.helpText;
  const fields = Object.fromEntries(
    Object.keys(defaults).map((key) => [key, keyed(merged[key], key)])
  );
  const changes = Object.fromEntries(
    Object.entries(fields).filter(([key, value]) => !isDeepStrictEqual(doc[key], value))
  );
  if (!Object.keys(changes).length) {
    console.log(`${doc._id}: bereits aktuell`);
    continue;
  }
  console.log(`${apply ? 'Schreibe' : 'Vorschau'} ${doc._id}: ${Object.keys(changes).join(', ')}`);
  transaction = transaction.patch(doc._id, (patch) => patch.ifRevisionId(doc._rev).set(changes));
  count++;
}
if (apply && count) {
  const result = await transaction.commit();
  console.log(
    `Übertragen: ${result.results.length} Dokument(e). Bestehende Entwürfe bleiben Entwürfe. Keine Dokumente gelöscht.`
  );
} else if (!apply) console.log('Nur Vorschau. Mit --apply veröffentlichen.');
